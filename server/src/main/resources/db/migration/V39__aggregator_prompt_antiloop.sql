-- ============================================================
-- V39 - aggregator prompt 加防循环纪律
--
-- 背景：聚合节点思考出现无意义字符循环（qwen3.7-flash thinking=1，实测单次
-- 42s~191s 烧满输出上限）。根因链：tavily 检索的网页快照携带编码破损片段
-- （U+FFFD 乱码/孤立代理）→ 专家忠实复制进交付物 → 原样拼进聚合 user →
-- 小模型思考解码器遇到非法 token 序列退化复读。
--
-- 双防线（与代码层配合）：harness 侧已做聚合输入净化（坏字符剥离 + URL 去重
-- 去查询参数 + 单条 6000 字符封顶，见 TextSanitizer.forAggregateInput）；
-- 本迁移在 prompt 加指示纪律，防线补在小模型行为侧。
--
-- REPLACE 写法幂等：NOT LIKE 守卫使重复执行零变更。
-- ============================================================

UPDATE `agent`
SET prompt = REPLACE(
        prompt,
        '忠实于各子结果，不改写结论、不编造事实。',
        '忠实于各子结果，不改写结论、不编造事实。汇总时不要逐字罗列来源 URL，标注域名或标题即可；遇到无法识别的乱码片段直接跳过，禁止复述。'
    )
WHERE agent_name = 'aggregator'
  AND prompt LIKE '%不改写结论、不编造事实。%'
  AND prompt NOT LIKE '%禁止复述%';

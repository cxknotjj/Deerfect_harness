-- lead 拆解输出协议升级：JSON 增加 brief 自包含任务书字段（动态子 Agent：模板 × 任务书）。
-- 执行专家不注入会话记忆、看不到对话记录，brief 必须写全四要素：
-- 目标（要达成什么）、背景（所需上下文与已知信息）、约束（工具使用与范围限制）、交付物（期望的输出形式），
-- 并禁止"参考上文"之类依赖对话记录的表述。
-- 可选专家清单与"至多 4 条"拆解数量约束均保持不动。
-- REPLACE 写法幂等：重复执行时目标子串已不存在，不再变更。
UPDATE `agent`
SET prompt = REPLACE(
        prompt,
        '{"subtasks":[{"desc":"子任务描述","agent":"专家名"}]}，不要任何解释。',
        '{"subtasks":[{"desc":"子任务描述","agent":"专家名","brief":"自包含任务书"}]}，不要任何解释。其中 brief 是给执行专家的完整任务书，必须自包含地写明四要素：目标（要达成什么）、背景（完成任务所需的上下文与已知信息）、约束（工具使用与范围限制）、交付物（期望的输出形式）；执行专家看不到会话历史，禁止写"参考上文"之类依赖对话记录的表述。'
    )
WHERE agent_name = 'lead'
  AND prompt LIKE '%{"subtasks":[{"desc":"子任务描述","agent":"专家名"}]}%';
